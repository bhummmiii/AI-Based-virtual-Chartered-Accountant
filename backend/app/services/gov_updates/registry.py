def seed_gov_sources(db: Session) -> int:
    """
    Idempotently seeds the gov_sources registry table.
    Inserts missing sources; preserves custom settings if already created.
    Returns count of newly inserted sources.
    """
    now = datetime.now(timezone.utc)
    inserted = 0

    for s_data in INITIAL_SOURCES:
        existing = db.query(GovSource).filter(GovSource.code == s_data["code"]).first()
        if not existing:
            source = GovSource(
                code=s_data["code"],
                name=s_data["name"],
                base_url=s_data["base_url"],
                domain=s_data["domain"],
                tier=s_data["tier"],
                scope=s_data["scope"],
                state_code=s_data["state_code"],
                method=s_data["method"],
                enabled=s_data["enabled"],
                status=s_data["status"],
                robots_ok=s_data["robots_ok"],
                captcha_detected=s_data["captcha_detected"],
                probe_date=now,
                tos_note=s_data["tos_note"],
                crawl_delay_seconds=s_data["crawl_delay_seconds"],
                last_error=s_data.get("last_error"),
            )
            db.add(source)
            inserted += 1

    if inserted > 0:
        db.commit()
    return inserted
